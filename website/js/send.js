const wallet = requireWallet();

// CCT_TRANSFER_FEE mirrors api/apply.go's CCTTransferFee - a flat CCT
// cost charged on every CCT send (not ETHTEST/USDCTEST/REPT/custom
// tokens), paid to the validator that confirms the block. Shown here
// so the fee isn't a surprise only discovered after submitting.
const CCT_TRANSFER_FEE = 1;

function currentSymbol() {
    return document.getElementById("sendSymbol").value;
}

async function refresh() {
    if (!wallet) return;

    const symbol = currentSymbol();
    document.getElementById("sendSymbolLabel").innerText = symbol;
    document.getElementById("sendAddressHint").style.display = symbol === "CCT" ? "none" : "block";
    const feeNote = document.getElementById("sendFeeNote");
    if (feeNote) {
        feeNote.innerText =
            symbol === "CCT" ? `A flat ${CCT_TRANSFER_FEE} CCT network fee applies on top of the amount sent.` : "";
    }

    try {
        const data = await fetchTokenBalance(wallet, symbol);
        document.getElementById("balance").innerText = data.balance;
    } catch (e) {
        console.error(e);
    }
}

async function send() {
    if (!wallet) return;

    const symbol = currentSymbol();
    // normalizeAddress strips an optional "cc" prefix - a user pasting
    // their own copied/QR'd address (which now always shows "cc...")
    // or an address typed without it should both work.
    const to = normalizeAddress(document.getElementById("toAddress").value.trim());
    const amount = parseFloat(document.getElementById("amount").value);

    if (!to || to.length !== 40) {
        alert("Enter a valid recipient address.");
        return;
    }

    if (isNaN(amount) || amount <= 0) {
        alert("Invalid amount.");
        return;
    }

    try {
        const result = await apiPostSigned("/token/transfer", {
            to,
            amount,
            symbol,
        });

        if (result.success === false) {
            alert(
                symbol === "CCT"
                    ? `Insufficient CCT - you need the amount plus the ${CCT_TRANSFER_FEE} CCT network fee.`
                    : "Insufficient balance."
            );
            return;
        }

        document.getElementById("sendStatus").innerText = result.fee
            ? `Sent (tx ${result.txId}) - ${result.fee} CCT network fee applied - takes effect once the next block confirms it.`
            : `Sent (tx ${result.txId}) - takes effect once the next block confirms it.`;

        setTimeout(refresh, 9000);
    } catch (e) {
        alert("Send failed: " + e.message);
    }
}

document.getElementById("sendSymbol").addEventListener("change", refresh);

// A page can deep-link straight into a preselected token (e.g.
// asset.html's Send button) via ?symbol=<SYMBOL>.
(function preselectSymbolFromQueryString() {
    const symbol = new URLSearchParams(window.location.search).get("symbol");
    const select = document.getElementById("sendSymbol");
    if (symbol && [...select.options].some((o) => o.value === symbol)) {
        select.value = symbol;
    }
})();

refresh();

// --- QR scanner ---------------------------------------------------
//
// Uses website/js/qr-decode.js, a QR reader hand-written for exactly
// what website/js/qrcode.js produces (see that file's header comment
// for why). Earlier this gated on the browser-native BarcodeDetector
// API, which only ships on Android Chrome/ChromeOS - absent on
// desktop Chrome/Edge/Firefox/Safari, so the scanner silently failed
// for nearly everyone. qr-decode.js works in any browser with
// <canvas>/getImageData, no camera-API version gap.

let scanStream = null;
let scanRafId = null;
let scanLastAttempt = 0;
const SCAN_THROTTLE_MS = 300; // full decode is too costly to run every animation frame

const scanCanvas = document.createElement("canvas");
const scanCanvasCtx = scanCanvas.getContext("2d", { willReadFrequently: true });
const SCAN_MAX_DIM = 900; // bounds decode cost for large camera frames/photos

// decodeImageSource draws any image-like source (a <video> frame or a
// decoded photo) onto a bounded-size offscreen canvas and runs
// QRDecode against it - shared by both the live-camera loop and the
// static-photo fallback below.
function decodeImageSource(source, sw, sh) {
    const scale = Math.min(1, SCAN_MAX_DIM / Math.max(sw, sh));
    const w = Math.max(1, Math.round(sw * scale));
    const h = Math.max(1, Math.round(sh * scale));
    scanCanvas.width = w;
    scanCanvas.height = h;
    scanCanvasCtx.drawImage(source, 0, 0, w, h);
    const imageData = scanCanvasCtx.getImageData(0, 0, w, h);
    return QRDecode.decode(imageData);
}

// isValidScannedAddress accepts both the legacy plain-hex format and
// the "cc"-prefixed format (see core/address.go) - a QR generated by
// an older client or the new one should both scan correctly.
function isValidScannedAddress(text) {
    return /^(cc)?[0-9a-f]{40}$/i.test(text);
}

async function openScanModal() {
    document.getElementById("scanModalOverlay").style.display = "flex";
    const statusEl = document.getElementById("scanStatus");
    statusEl.innerText = "Requesting camera access...";

    // Everything past this point can fail in ways that would otherwise
    // leave the camera stream open with no visible error - one
    // try/catch around the whole setup guarantees closeScanModal's
    // cleanup always runs instead of leaking the camera indefinitely.
    try {
        scanStream = await navigator.mediaDevices.getUserMedia({ video: { facingMode: "environment" } });

        const video = document.getElementById("scanVideo");
        video.srcObject = scanStream;
        // autoplay isn't reliably honored on every browser once the
        // stream is assigned programmatically after an async gap (most
        // notably Safari) - an explicit play() closes that gap.
        await video.play().catch(() => {});

        statusEl.innerText = "Point your camera at a wallet address QR code.";

        const scanFrame = () => {
            if (!scanStream) return;

            const now = performance.now();
            if (now - scanLastAttempt >= SCAN_THROTTLE_MS && video.videoWidth > 0) {
                scanLastAttempt = now;
                try {
                    const text = decodeImageSource(video, video.videoWidth, video.videoHeight);
                    if (text) {
                        if (isValidScannedAddress(text.trim())) {
                            document.getElementById("toAddress").value = text.trim();
                            document.getElementById("sendStatus").innerText = "Address scanned.";
                            closeScanModal();
                            return;
                        }
                        statusEl.innerText = "That QR code isn't a recognized wallet address - keep trying.";
                    }
                } catch (e) {
                    console.error(e);
                }
            }

            scanRafId = requestAnimationFrame(scanFrame);
        };
        scanRafId = requestAnimationFrame(scanFrame);
    } catch (e) {
        statusEl.innerText = "Camera unavailable: " + e.message + " - use \"take or choose a photo\" below instead.";
        closeScanModal({ keepModalOpen: true });
    }
}

// scanFromFile decodes a single still image (from the camera app or
// photo library) - a fallback path that works even when live
// getUserMedia video is denied/unreliable.
async function scanFromFile(file) {
    const statusEl = document.getElementById("scanStatus");
    if (!file) return;

    try {
        const bitmap = await createImageBitmap(file);
        const text = decodeImageSource(bitmap, bitmap.width, bitmap.height);

        if (!text) {
            statusEl.innerText = "No QR code found in that photo - try again with a clearer, well-lit shot.";
            return;
        }

        if (!isValidScannedAddress(text.trim())) {
            statusEl.innerText = "That QR code isn't a recognized wallet address.";
            return;
        }

        document.getElementById("toAddress").value = text.trim();
        document.getElementById("sendStatus").innerText = "Address scanned.";
        closeScanModal();
    } catch (e) {
        statusEl.innerText = "Couldn't read that photo: " + e.message;
    }
}

function closeScanModal(opts) {
    if (!opts || !opts.keepModalOpen) {
        document.getElementById("scanModalOverlay").style.display = "none";
    }

    if (scanRafId) {
        cancelAnimationFrame(scanRafId);
        scanRafId = null;
    }
    if (scanStream) {
        scanStream.getTracks().forEach((t) => t.stop());
        scanStream = null;
    }
}

document.getElementById("scanFileInput").addEventListener("change", (e) => {
    const file = e.target.files && e.target.files[0];
    scanFromFile(file);
    e.target.value = "";
});
